const {API_URL,ANON_KEY,SERVICE_ROLE_KEY}=process.env;
assert.ok(API_URL&&ANON_KEY&&SERVICE_ROLE_KEY,'Run against a disposable Supabase instance');
async function request(path,{token=ANON_KEY,key=ANON_KEY,method='GET',data,expected=200,body,contentType='application/json'}={}){
 const response=await fetch(API_URL+path,{method,headers:{apikey:key,Authorization:'Bearer '+token,'Content-Type':contentType,Prefer:'return=representation'},body:body??(data===undefined?undefined:JSON.stringify(data))});
 const text=await response.text();
 assert.ok([expected].flat().includes(response.status),method+' '+path.split('?')[0]+' → '+response.status+' '+text.slice(0,600));
 return text?JSON.parse(text):null;
}
